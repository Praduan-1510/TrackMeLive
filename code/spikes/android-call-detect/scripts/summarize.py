#!/usr/bin/env python3
"""Turns the raw evidence from emulator-run.sh (or a real-device run) into one timeline per scenario.

    python3 scripts/summarize.py results/emulator > results/emulator/TIMELINE.md

Merges, on the device clock: Telecom's call state changes, Telecom's setMode requests, AudioService's
actual mode changes (dumpsys audio history), and the spike's own events. Heartbeats, probes and
playback lines are left out; they stay in the raw files.
"""
import pathlib
import re
import sys

KEEP = {"START", "MODE_CB", "MODE_POLL", "TELEPHONY", "DERIVED", "RECEIVER", "GAP", "FGS", "UI", "PERM", "SELFTEST"}
STATE = {"0": "IDLE", "1": "RINGING", "2": "OFFHOOK"}


def spike_line(time, text):
    parts = [p.strip() for p in text.split("|")]
    if len(parts) < 3 or parts[0] not in KEEP:
        return None
    source, message, state = parts[0], parts[1], parts[2]
    state = state.replace("imp=", "").replace(" ui=", "/").replace(" fgs=", "/fgs=")
    return (time, f"app {source}", f"{message} [{state}]")


def telecom_line(time, text):
    m = re.search(r"setCallState (\w+) -> (\w+)", text)
    if m:
        return (time, "Telecom", f"call {m.group(1)} -> {m.group(2)}")
    m = re.search(r"Broadcasted state change: (\d)", text)
    if m:
        return (time, "Telecom", f"device call state {STATE.get(m.group(1), m.group(1))} (what TelephonyCallback and PHONE_STATE get)")
    m = re.search(r"AudioManager#setMode\(([^)]+)\)", text)
    if m:
        return (time, "Telecom", f"asks AudioService for setMode({m.group(1)})")
    return None


def scenario(logcat: pathlib.Path):
    rows = []
    first = last = None
    for raw in logcat.read_text(errors="replace").splitlines():
        m = re.match(r"\d\d-\d\d (\d\d:\d\d:\d\d\.\d\d\d) [A-Z]/(\w+)\s*\(\s*\d+\): (.*)", raw)
        if not m:
            continue
        time, tag, text = m.groups()
        row = spike_line(time, text) if tag == "CallSpike" else telecom_line(time, text)
        if row:
            rows.append(row)
            first = first or time
            last = time
    audio = logcat.with_name(logcat.name.replace(".logcat.txt", ".audio.txt"))
    if audio.exists() and first:
        for raw in audio.read_text(errors="replace").splitlines():
            m = re.match(r"\d\d-\d\d (\d\d:\d\d:\d\d):(\d\d\d) setMode\((\w+)\) from package=(\S+).*selected mode=(\w+)", raw)
            if m:
                time = f"{m.group(1)}.{m.group(2)}"
                if first <= time <= last:
                    rows.append((time, "AudioService", f"mode is now {m.group(5)} (requested {m.group(3)} by {m.group(4)})"))
    rows.sort(key=lambda r: r[0])
    return rows


def main():
    folder = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "results/emulator")
    def order(path):
        m = re.match(r"s(\d+)([a-z]?)_", path.name)
        return (int(m.group(1)), m.group(2)) if m else (999, path.name)

    print("# Emulator timelines\n")
    print("Generated by scripts/summarize.py from the raw files next to this one. Device clock.\n")
    for logcat in sorted(folder.glob("*.logcat.txt"), key=order):
        name = logcat.name.replace(".logcat.txt", "")
        host = logcat.with_name(f"{name}.host.txt")
        title = ""
        if host.exists():
            head = host.read_text(errors="replace").splitlines()
            if head:
                title = head[0].split("=== ", 1)[-1]
        print(f"### {title or name}\n")
        print("| Time (device) | Who | What |\n| --- | --- | --- |")
        for time, who, what in scenario(logcat):
            print(f"| {time} | {who} | {what.replace('|', '/')} |")
        if host.exists():
            print("\nHost steps:\n")
            for line in host.read_text(errors="replace").splitlines()[1:]:
                print(f"    {line}")
        print()


if __name__ == "__main__":
    main()
