# shellcheck shell=bash
# Shared setup for run.sh and test.sh. Source it; don't run it.
# Sets: BACKEND_DIR, FIREBASE (array), JAVA_HOME, PATH, JAVA_TOOL_OPTIONS, and the dev
# emulator set's PROJECT_ID, EMULATOR_CONFIG and ports (use_emulator_set test switches them).

BACKEND_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FIREBASE_TOOLS_VERSION="15.32.1"
FIREBASE=(npx -y "firebase-tools@${FIREBASE_TOOLS_VERSION}")

# Two emulator sets, so a test run never touches the session the apps use:
#   dev   ./run.sh: project demo-trackmelive, firebase.json. The apps, the viewer and QA
#         connect here; its data is theirs.
#   test  ./test.sh (and ./run.sh --test): project demo-trackmelive-test, firebase.test.json,
#         distinct ports, no UI. Every test run wipes its data.
# Both can run at once. Keep the ports in sync with those files.
DEV_PROJECT_ID="demo-trackmelive"
TEST_PROJECT_ID="demo-trackmelive-test"
use_emulator_set() {
  case "$1" in
    dev)
      PROJECT_ID="${DEV_PROJECT_ID}"
      EMULATOR_CONFIG="${BACKEND_DIR}/firebase.json"
      AUTH_PORT=9099 FIRESTORE_PORT=8080 FUNCTIONS_PORT=5001 HUB_PORT=4400
      HOSTING_PORT=5050 UI_PORT=4000
      ;;
    test)
      PROJECT_ID="${TEST_PROJECT_ID}"
      EMULATOR_CONFIG="${BACKEND_DIR}/firebase.test.json"
      AUTH_PORT=9199 FIRESTORE_PORT=8180 FUNCTIONS_PORT=5101 HUB_PORT=4410
      HOSTING_PORT="" UI_PORT=""
      ;;
    *)
      echo "error: unknown emulator set '$1' (dev or test)" >&2
      return 1
      ;;
  esac
}
use_emulator_set dev

# The test set's CLI and emulator logs (firebase-debug.log, firestore-debug.log). The CLI
# writes them to its working folder, so test runs work from here and never overwrite the
# dev set's logs in code/backend. Gitignored.
TEST_LOG_DIR="${BACKEND_DIR}/test-logs"

# The Functions emulator reads params (VIEWER_ORIGIN) from functions/.env.<project id>.
# The test project uses the demo project's, copied here on each run and gitignored, so
# there's one params file to keep up and one .env file in git.
write_test_params() {
  local src="${BACKEND_DIR}/functions/.env.${DEV_PROJECT_ID}"
  {
    echo "# Generated by scripts/env.sh from .env.${DEV_PROJECT_ID} for the test emulator set. Don't edit."
    cat "${src}"
  } > "${BACKEND_DIR}/functions/.env.${TEST_PROJECT_ID}"
}

# The emulators are Java programs, and firebase-tools 15 refuses Java older
# than 21. The Android build on this machine pins JDK 17 in JAVA_HOME, so don't
# trust an inherited JAVA_HOME: use EMULATOR_JAVA_HOME if set, else a JDK 21+
# that macOS knows about, else JAVA_HOME if it is 21+.
# The version line isn't always first: a JAVA_TOOL_OPTIONS (this file sets one) adds a
# "Picked up JAVA_TOOL_OPTIONS" line before it.
java_major() { "$1/bin/java" -version 2>&1 | sed -nE 's/.*version "([0-9]+).*/\1/p' | head -n 1; }
if [[ -n "${EMULATOR_JAVA_HOME:-}" ]]; then
  JAVA_HOME="${EMULATOR_JAVA_HOME}"
elif [[ -x /usr/libexec/java_home ]] && found="$(/usr/libexec/java_home -v 21+ 2>/dev/null)"; then
  JAVA_HOME="${found}"
fi
if [[ -z "${JAVA_HOME:-}" || ! -x "${JAVA_HOME}/bin/java" || "$(java_major "${JAVA_HOME}")" -lt 21 ]]; then
  echo "error: the Firebase emulators need JDK 21 or newer. Install Temurin 21, or set EMULATOR_JAVA_HOME." >&2
  return 1 2>/dev/null || exit 1
fi
export JAVA_HOME
export PATH="${JAVA_HOME}/bin:${PATH}"

# Java's dual-stack sockets fail HTTPS handshakes in some sandboxed shells on
# this machine; IPv4 avoids that and is harmless elsewhere.
case " ${JAVA_TOOL_OPTIONS:-} " in
  *preferIPv4Stack*) ;;
  *) export JAVA_TOOL_OPTIONS="${JAVA_TOOL_OPTIONS:+${JAVA_TOOL_OPTIONS} }-Djava.net.preferIPv4Stack=true" ;;
esac

# Install a package's dependencies from its lockfile when node_modules is missing
# or older than the lockfile.
ensure_deps() {
  local dir="$1"
  if [[ ! -d "${dir}/node_modules" || "${dir}/package-lock.json" -nt "${dir}/node_modules/.package-lock.json" ]]; then
    echo "==> npm ci in ${dir#"${BACKEND_DIR}/"}"
    npm ci --prefix "${dir}" --no-audit --no-fund
  fi
}

build_functions() {
  ensure_deps "${BACKEND_DIR}/functions"
  echo "==> building functions"
  npm --prefix "${BACKEND_DIR}/functions" run --silent build
}
