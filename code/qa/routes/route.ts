/**
 * Simulated routes: one JSON format that the fake sharer, the Android emulator player and the iOS
 * Simulator (through GPX) all read. A route is a list of fixes, one a second, each with its time
 * from the start, position, horizontal accuracy, speed and course:
 *
 *   {
 *     "format": "tml-route/1",
 *     "id": "walk-ferry-building",
 *     "title": "…", "mode": "walk" | "drive" | "stop-and-go", "summary": "…",
 *     "duration_s": 512, "distance_m": 716,
 *     "points": [{ "t_s": 0, "lat": 37.79475, "lng": -122.3959, "accuracy_m": 6, "speed_mps": 0, "course_deg": 72 }, …]
 *   }
 *
 * The routes are generated by build-routes.ts (deterministic; `--check` verifies the files are
 * current). No dependencies: Node runs this file as TypeScript (type stripping).
 */

import { readFileSync, readdirSync } from 'node:fs';
import { basename, dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROUTE_FORMAT = 'tml-route/1';
export const ROUTES_DIR = dirname(fileURLToPath(import.meta.url));

export type RouteMode = 'walk' | 'drive' | 'stop-and-go';

export interface RoutePoint {
  /** Seconds from the start of the route. */
  readonly t_s: number;
  readonly lat: number;
  readonly lng: number;
  /** Horizontal accuracy in meters, as a phone would report it. */
  readonly accuracy_m: number;
  readonly speed_mps: number;
  /** Degrees clockwise from north. */
  readonly course_deg: number;
}

export interface Route {
  readonly format: typeof ROUTE_FORMAT;
  readonly id: string;
  readonly title: string;
  readonly mode: RouteMode;
  readonly summary: string;
  readonly duration_s: number;
  readonly distance_m: number;
  readonly points: readonly RoutePoint[];
}

const MODES: readonly RouteMode[] = ['walk', 'drive', 'stop-and-go'];

/** Throws with every problem found, so a broken route file says exactly what's wrong. */
export function validateRoute(value: unknown, where = 'route'): Route {
  const problems: string[] = [];
  const r = value as Partial<Route> | null;
  if (typeof r !== 'object' || r === null) throw new Error(`${where}: not a JSON object`);
  if (r.format !== ROUTE_FORMAT) problems.push(`format must be "${ROUTE_FORMAT}", got ${JSON.stringify(r.format)}`);
  if (typeof r.id !== 'string' || !/^[a-z0-9-]+$/.test(r.id)) problems.push('id must be lowercase letters, digits and dashes');
  if (typeof r.title !== 'string' || r.title === '') problems.push('title is missing');
  if (typeof r.summary !== 'string') problems.push('summary is missing');
  if (!MODES.includes(r.mode as RouteMode)) problems.push(`mode must be one of ${MODES.join(', ')}`);
  if (!Array.isArray(r.points) || r.points.length < 2) {
    problems.push('points must hold at least two fixes');
  } else {
    let prev = -Infinity;
    r.points.forEach((p, i) => {
      const bad = (what: string): void => {
        if (problems.length < 20) problems.push(`points[${String(i)}]: ${what}`);
      };
      if (typeof p.t_s !== 'number' || !Number.isFinite(p.t_s)) bad('t_s is not a number');
      else if (p.t_s <= prev) bad(`t_s ${String(p.t_s)} is not after ${String(prev)}`);
      if (i === 0 && p.t_s !== 0) bad('the first fix must be at t_s 0');
      if (typeof p.lat !== 'number' || p.lat < -90 || p.lat > 90) bad('lat out of range');
      if (typeof p.lng !== 'number' || p.lng < -180 || p.lng > 180) bad('lng out of range');
      if (typeof p.accuracy_m !== 'number' || !(p.accuracy_m > 0)) bad('accuracy_m must be above 0');
      if (typeof p.speed_mps !== 'number' || p.speed_mps < 0) bad('speed_mps must be 0 or more');
      if (typeof p.course_deg !== 'number' || p.course_deg < 0 || p.course_deg >= 360) bad('course_deg must be in [0, 360)');
      prev = p.t_s;
    });
    const last = r.points[r.points.length - 1];
    if (last && r.duration_s !== last.t_s) problems.push(`duration_s ${String(r.duration_s)} isn't the last fix's t_s ${String(last.t_s)}`);
  }
  if (problems.length > 0) throw new Error(`${where} is not a valid ${ROUTE_FORMAT} route:\n  ${problems.join('\n  ')}`);
  return r as Route;
}

/** The route ids in this folder (each <id>.json). */
export function routeIds(): string[] {
  return readdirSync(ROUTES_DIR)
    .filter((f) => f.endsWith('.json') && f !== 'package.json')
    .map((f) => basename(f, '.json'))
    .sort();
}

/** Loads a route by id (a file in this folder) or by path. */
export function loadRoute(idOrPath: string): Route {
  const path = idOrPath.endsWith('.json') ? (isAbsolute(idOrPath) ? idOrPath : resolve(idOrPath)) : join(ROUTES_DIR, `${idOrPath}.json`);
  let text: string;
  try {
    text = readFileSync(path, 'utf8');
  } catch {
    throw new Error(`No route "${idOrPath}" (looked for ${path}). Routes: ${routeIds().join(', ')}`);
  }
  return validateRoute(JSON.parse(text) as unknown, path);
}

const lerp = (a: number, b: number, k: number): number => a + (b - a) * k;

/**
 * Where the route is at `t` seconds: linear between the fixes around it, clamped to the ends.
 * Accuracy and speed are interpolated too; the course is the earlier fix's.
 */
export function positionAt(route: Route, t: number): RoutePoint {
  const pts = route.points;
  const first = pts[0];
  const last = pts[pts.length - 1];
  if (!first || !last) throw new Error(`route ${route.id} has no points`);
  if (t <= 0) return first;
  if (t >= last.t_s) return last;
  // Binary search for the last fix at or before t.
  let lo = 0;
  let hi = pts.length - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if ((pts[mid] as RoutePoint).t_s <= t) lo = mid;
    else hi = mid;
  }
  const a = pts[lo] as RoutePoint;
  const b = pts[hi] as RoutePoint;
  const k = (t - a.t_s) / (b.t_s - a.t_s);
  return {
    t_s: t,
    lat: lerp(a.lat, b.lat, k),
    lng: lerp(a.lng, b.lng, k),
    accuracy_m: lerp(a.accuracy_m, b.accuracy_m, k),
    speed_mps: lerp(a.speed_mps, b.speed_mps, k),
    course_deg: a.course_deg,
  };
}

const EARTH_M = 6_371_008.8;
const rad = (d: number): number => (d * Math.PI) / 180;

/** Great-circle distance in meters. */
export function distanceMeters(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const dLat = rad(b.lat - a.lat);
  const dLng = rad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_M * Math.asin(Math.min(1, Math.sqrt(h)));
}

/** Initial bearing from a to b, degrees clockwise from north, in [0, 360). */
export function bearingDegrees(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const y = Math.sin(rad(b.lng - a.lng)) * Math.cos(rad(b.lat));
  const x = Math.cos(rad(a.lat)) * Math.sin(rad(b.lat)) - Math.sin(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.cos(rad(b.lng - a.lng));
  return ((Math.atan2(y, x) * 180) / Math.PI + 360) % 360;
}

/** Shared option parsing for the speed factor (route seconds per real second). */
export function parseSpeedFactor(raw: string | undefined): number {
  if (raw === undefined) return 1;
  const n = Number(raw);
  if (!Number.isFinite(n) || n <= 0 || n > 1000) throw new Error(`--speed must be a number above 0 and at most 1000, got "${raw}"`);
  return n;
}

/** Shared option parsing for a fixed accuracy override, in meters. */
export function parseAccuracy(raw: string | undefined): number | null {
  if (raw === undefined || raw === 'route') return null;
  const n = Number(raw);
  if (!Number.isFinite(n) || n <= 0 || n > 10_000) throw new Error(`--accuracy must be meters above 0 (or "route"), got "${raw}"`);
  return n;
}

/** Whether the module with this import.meta.url is the script Node was started with. */
export function isMain(importMetaUrl: string): boolean {
  const script = process.argv[1];
  return script !== undefined && fileURLToPath(importMetaUrl) === resolve(script);
}
