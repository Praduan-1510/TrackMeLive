// Builds components/Mascot3D/preview.html from the three.js models in mascots/model/,
// so the design system's live 3D card always matches the models.
// The fallback stills point at the Mascots asset group's blobs in design-system.json.
//   node design-system/tools/build-mascot-preview.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ds = path.resolve(here, '..');
const model = path.resolve(ds, '../mascots/model');

const strip = (src) => src
  .replace(/^import .*$/gm, '')
  .replace(/^export const /gm, 'const ')
  .replace(/^export function /gm, 'function ');
// cast.mjs, accessories.mjs and mascots.mjs share helper names, so the cast and the
// accessories each get their own scope.
const scoped = (file, names) => `const { ${names} } = (() => {\n${strip(fs.readFileSync(path.join(model, file), 'utf8'))}\nreturn { ${names} };\n})();\n`;
const code = `${scoped('cast.mjs', 'CAST, ACCENTS')}\n${scoped('accessories.mjs', 'addAccessory, ACCESSORY_SUPPORT, ACCESSORIES')}\n${strip(fs.readFileSync(path.join(model, 'mascots.mjs'), 'utf8'))}`;

const blobs = JSON.parse(fs.readFileSync(path.join(ds, 'design-system.json'), 'utf8')).assetGroups.Mascots.files;
const still = (id) => (blobs[`${id}.png`] ? `/_blob/${blobs[`${id}.png`].blob}` : '');

const SETS = [
  { id: 'classics', name: 'Classics', cast: [['fox', 'Fox', 'Default · velvet fur'], ['ghost', 'Ghost', 'Soft vinyl'], ['robot', 'Robot', 'Brushed steel'], ['astronaut', 'Astronaut', 'Iridescent visor']] },
  { id: 'anime', name: 'Anime', cast: [['hero', 'Hero', 'Goggles up, hair on fire'], ['star', 'Star', 'Sakura bob, star clip'], ['ninja', 'Ninja', 'Eyes only'], ['neko', 'Neko', 'Cat-ear hoodie']] },
  { id: 'movie', name: 'Movie night', cast: [['ace', 'Ace', 'Aviators and a bomber'], ['detective', 'Detective', 'Fedora and trench'], ['cowboy', 'Cowboy', 'Cattleman crease'], ['agent', 'Agent', 'Velvet tux, one brow up']] },
];

const html = `<!-- @dsCard group="Mascots" height=420 width=960 subtitle="Live 3D models, three.js r160. Generated by tools/build-mascot-preview.mjs" -->
<div class="tml-m3d" id="tml-m3d">
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Gabarito:wght@500;600;700;800&family=Figtree:wght@400;500;600;700&display=swap">
  <style>
    .tml-m3d { position: relative; width: 960px; height: 420px; overflow: hidden; background: var(--ground); font-family: var(--font-text); color: var(--ink); }
    .tml-m3d .sets { position: absolute; left: 50%; top: 14px; transform: translateX(-50%); display: grid; grid-auto-flow: column; grid-auto-columns: 132px; padding: 2px; border-radius: 10px; background: var(--surface-raised); }
    .tml-m3d .sets button { min-height: 32px; border: 0; border-radius: 8px; background: transparent; color: var(--ink); font: 600 13px var(--font-text); cursor: pointer; }
    .tml-m3d .sets button[aria-pressed="true"] { background: var(--surface); box-shadow: 0 1px 3px rgba(0, 0, 0, .12); }
    .tml-m3d .sets button:focus-visible { outline: 3px solid var(--focus-ring); outline-offset: 2px; }
    .tml-m3d .stage, .tml-m3d .stills { position: absolute; left: 0; top: 60px; width: 960px; height: 280px; }
    .tml-m3d .stage canvas { display: block; }
    .tml-m3d .stills, .tml-m3d .names { display: none; grid-template-columns: repeat(4, minmax(0, 1fr)); }
    .tml-m3d .stills.on, .tml-m3d .names.on { display: grid; }
    .tml-m3d .stills img { display: block; width: 236px; height: 236px; margin: 22px auto 0; object-fit: contain; }
    .tml-m3d.live .stills { visibility: hidden; }
    .tml-m3d .names { position: absolute; left: 0; right: 0; top: 346px; text-align: center; }
    .tml-m3d .names b { display: block; font-family: var(--font-display); font-size: 17px; line-height: 22px; font-weight: 800; }
    .tml-m3d .names span { font-size: 13px; line-height: 18px; color: var(--ink-secondary); }
  </style>
  <div class="sets" role="group" aria-label="Mascot set">
${SETS.map((s, i) => `    <button type="button" data-set="${s.id}" aria-pressed="${i === 0}">${s.name}</button>`).join('\n')}
  </div>
${SETS.map((s, i) => `  <div class="stills${i === 0 ? ' on' : ''}" data-set="${s.id}" aria-hidden="true">
${s.cast.map(([id]) => `    <img src="${still(id)}" alt="">`).join('\n')}
  </div>`).join('\n')}
  <div class="stage" role="img" aria-label="Four mascots of the chosen set in 3D, gently turning"></div>
${SETS.map((s, i) => `  <div class="names${i === 0 ? ' on' : ''}" data-set="${s.id}">
${s.cast.map(([, n, d]) => `    <div><b>${n}</b><span>${d}</span></div>`).join('\n')}
  </div>`).join('\n')}
  <script type="module">
import * as THREE from 'https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.module.js';

${code}

const root = document.getElementById('tml-m3d');
const LINEUP = ${JSON.stringify(Object.fromEntries(SETS.map((s) => [s.id, s.cast.map(([id]) => id)])))};
try {
  const host = root.querySelector('.stage');
  const W = 960, H = 280, N = 4, VW = W / N;
  const renderer = new THREE.WebGLRenderer({ antialias: true, alpha: true });
  renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));
  renderer.setSize(W, H);
  renderer.setClearColor(0x000000, 0);
  renderer.setScissorTest(true);
  const { scene } = createStage(THREE, renderer, VW / H);
  const built = {};
  // Models are built the first time their set is shown.
  const itemsFor = (set) => built[set] || (built[set] = LINEUP[set].map((name) => {
    const m = buildMascot(THREE, name);
    m.visible = false;
    scene.add(m);
    const cam = new THREE.PerspectiveCamera(26, VW / H, 0.1, 100);
    frame(THREE, cam, m, 1.16);
    return { m, cam, inner: m.children[0] };
  }));
  let set = 'classics';
  let items = itemsFor(set);
  host.appendChild(renderer.domElement);
  root.classList.add('live');
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const all = () => Object.values(built).flat();
  const draw = (t) => {
    items.forEach((it, i) => {
      if (!reduce) {
        it.inner.rotation.y = 0.32 + 0.38 * Math.sin(t * 0.0006 + i * 1.3);
        it.m.position.y = 0.05 * Math.sin(t * 0.0016 + i);
      }
      all().forEach((o) => { o.m.visible = o === it; });
      renderer.setViewport(i * VW, 0, VW, H);
      renderer.setScissor(i * VW, 0, VW, H);
      renderer.render(scene, it.cam);
    });
  };
  root.querySelectorAll('.sets button').forEach((b) => b.addEventListener('click', () => {
    set = b.dataset.set;
    items = itemsFor(set);
    root.querySelectorAll('.sets button').forEach((x) => x.setAttribute('aria-pressed', String(x === b)));
    root.querySelectorAll('.stills, .names').forEach((x) => x.classList.toggle('on', x.dataset.set === set));
    if (reduce) draw(0);
  }));
  if (reduce) draw(0); else renderer.setAnimationLoop(draw);
} catch (e) {
  root.classList.remove('live');
  root.querySelectorAll('.sets button').forEach((b) => b.addEventListener('click', () => {
    root.querySelectorAll('.sets button').forEach((x) => x.setAttribute('aria-pressed', String(x === b)));
    root.querySelectorAll('.stills, .names').forEach((x) => x.classList.toggle('on', x.dataset.set === b.dataset.set));
  }));
}
  </script>
</div>
`;
fs.writeFileSync(path.join(ds, 'components/Mascot3D/preview.html'), html);
console.log('wrote components/Mascot3D/preview.html', html.length, 'bytes');
